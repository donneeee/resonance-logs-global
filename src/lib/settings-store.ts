export function notifySettingsChanged(): void {
  if (typeof window === "undefined") return;
  if (settingsChangedTimer) clearTimeout(settingsChangedTimer);
  settingsChangedTimer = setTimeout(() => {
    settingsChangedTimer = null;
    void persistCurrentLiveSettingsStores()
      .catch((error) => {
        console.warn("Failed to persist live settings before broadcast:", error);
      })
      .then(() => import("@tauri-apps/api/event"))
      .then(({ emit }) => emit(SETTINGS_CHANGED_EVENT))
      .catch((error) => {
        console.warn("Failed to broadcast settings update:", error);
      });
  }, 75);
}

function isMutableRecord(value: unknown): value is MutableRecord {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function cloneSettingValue<T>(value: T): T {
  if (Array.isArray(value)) {
    return value.map((item) => cloneSettingValue(item)) as T;
  }
  if (isMutableRecord(value)) {
    const next: MutableRecord = {};
    for (const [key, item] of Object.entries(value)) {
      next[key] = cloneSettingValue(item);
    }
    return next as T;
  }
  return value;
}

function replaceRecordContents<T extends MutableRecord>(target: T, source: T): void {
  for (const key of Object.keys(target)) {
    if (!Object.prototype.hasOwnProperty.call(source, key)) {
      delete target[key];
    }
  }
  Object.assign(target, source);
}

function mergeDeepDefaults<T extends MutableRecord>(
  target: T,
  defaults: Record<string, unknown>,
): void {
  const mutableTarget = target as MutableRecord;
  for (const [key, value] of Object.entries(defaults)) {
    const current = mutableTarget[key];
    if (current === undefined) {
      mutableTarget[key] = cloneSettingValue(value);
      continue;
    }
    if (isMutableRecord(current) && isMutableRecord(value)) {
      mergeDeepDefaults(current, value);
    }
  }
}

function countKnownSettingKeys(
  value: MutableRecord,
  defaults: Record<string, unknown>,
): number {
  let count = 0;
  for (const key of Object.keys(defaults)) {
    if (Object.prototype.hasOwnProperty.call(value, key)) count += 1;
  }
  return count;
}

function unwrapPersistedSettingsPayload(
  value: unknown,
  defaults: Record<string, unknown>,
): unknown {
  if (!isMutableRecord(value)) return value;

  const directKnownKeys = countKnownSettingKeys(value, defaults);
  let bestPayload: unknown = value;
  let bestKnownKeys = directKnownKeys;

  for (const wrapperKey of ["state", "value", "settings"]) {
    const candidate = value[wrapperKey];
    if (!isMutableRecord(candidate)) continue;
    const candidateKnownKeys = countKnownSettingKeys(candidate, defaults);
    if (candidateKnownKeys > bestKnownKeys || (bestKnownKeys === 0 && candidateKnownKeys > 0)) {
      bestPayload = candidate;
      bestKnownKeys = candidateKnownKeys;
    }
  }

  return bestPayload;
}

function normalizeObjectWithDefaults<T extends MutableRecord>(
  value: unknown,
  defaults: T,
): T {
  const payload = unwrapPersistedSettingsPayload(value, defaults);
  const next = isMutableRecord(payload)
    ? (cloneSettingValue(payload) as MutableRecord)
    : {};
  mergeDeepDefaults(next, defaults);
  return next as T;
}

function normalizeBooleanValue(value: unknown, fallback: boolean): boolean {
  if (typeof value === "boolean") return value;
  if (typeof value === "number") return value !== 0;
  if (typeof value === "string") {
    const normalized = value.trim().toLowerCase();
    if (normalized === "true" || normalized === "1") return true;
    if (normalized === "false" || normalized === "0") return false;
  }
  return fallback;
}

function normalizeBooleanSettingsState<T extends MutableRecord>(
  value: unknown,
  defaults: T,
): T {
  const next = normalizeObjectWithDefaults(value, defaults) as MutableRecord;
  for (const [key, defaultValue] of Object.entries(defaults)) {
    if (typeof defaultValue === "boolean") {
      next[key] = normalizeBooleanValue(next[key], defaultValue);
    }
  }
  return next as T;
}

function cloneHistorySummaryDefaults(): HistorySummarySettings {
  return cloneSettingValue(DEFAULT_HISTORY_SUMMARY_FIELDS) as HistorySummarySettings;
}

function normalizeHistorySummarySettingsState(value: unknown): HistorySummarySettings {
  const defaults = cloneHistorySummaryDefaults();
  const payload = normalizeObjectWithDefaults(
    value,
    defaults as unknown as MutableRecord,
  ) as MutableRecord;
  const next = cloneHistorySummaryDefaults() as unknown as MutableRecord;

  for (const [groupKey, defaultGroup] of Object.entries(defaults)) {
    next[groupKey] = normalizeBooleanSettingsState(
      isMutableRecord(payload[groupKey]) ? payload[groupKey] : {},
      defaultGroup as unknown as MutableRecord,
    );
  }

  return next as unknown as HistorySummarySettings;
}

function normalizeColumnOrder(
  target: { order?: string[] },
  defaults: readonly string[],
): void {
  const current = Array.isArray(target.order) ? target.order : [];
  const defaultSet = new Set(defaults);
  const deduped = current.filter(
    (key, index) => defaultSet.has(key) && current.indexOf(key) === index,
  );

  for (const key of defaults) {
    if (!deduped.includes(key)) deduped.push(key);
  }

  target.order = deduped;
}

function normalizeColumnOrderSettingsState(
  defaults: readonly string[],
): SettingsStoreNormalizer<{ order: string[] }> {
  return (value: unknown) => {
    const next = normalizeObjectWithDefaults(value, {
      order: [...defaults],
    }) as { order: string[] };
    normalizeColumnOrder(next, defaults);
    return next;
  };
}

function normalizeLiveSortSettingsState<T extends { sortKey: string; sortDesc: boolean }>(
  value: unknown,
  defaults: T,
): T {
  const next = normalizeObjectWithDefaults(value, defaults) as T;
  if (typeof next.sortKey !== "string" || !next.sortKey.trim()) {
    next.sortKey = defaults.sortKey;
  }
  next.sortDesc = normalizeBooleanValue(next.sortDesc, defaults.sortDesc);
  return next;
}

